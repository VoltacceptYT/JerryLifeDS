#!/usr/bin/env python3
"""Convert assets/sfx/jerry_click.ogg to an 8-bit signed PCM array (source/clickdata.c).

    python3 tools/convert_sfx.py [--rate 22050]

Needs ffmpeg + numpy. The generated file is committed, so normal builds don't need this.
"""
import argparse, os, subprocess
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--rate", type=int, default=22050)
a = ap.parse_args()
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
src = os.path.join(root, "assets", "sfx", "jerry_click.ogg")
raw = subprocess.run(["ffmpeg", "-hide_banner", "-v", "error", "-i", src, "-ac", "1", "-ar", str(a.rate),
                      "-f", "f32le", "-"], check=True, stdout=subprocess.PIPE).stdout
x = np.frombuffer(raw, dtype="<f4").astype(np.float64)
peak = np.max(np.abs(x)) or 1.0
x = x / peak * 0.95                      # normalise: 8-bit has little headroom to waste
pcm = np.clip(np.round(x * 127), -127, 127).astype(np.int8)
pad = (-len(pcm)) % 4                     # hardware wants whole words
pcm = np.concatenate([pcm, np.zeros(pad, np.int8)])
body = ",".join(str(int(v)) for v in pcm)
out = ("// Generated by tools/convert_sfx.py - do not edit.\n#include <stdint.h>\n"
       "const int8_t click_pcm[%d] __attribute__((aligned(4))) = {%s};\n"
       "const unsigned click_pcm_len = %d;\nconst unsigned click_pcm_rate = %d;\n") % (len(pcm), body, len(pcm), a.rate)
with open(os.path.join(root, "source", "clickdata.c"), "w", newline="\n") as f:
    f.write(out)
print("click: %d samples @ %d Hz (%.2f s)" % (len(pcm), a.rate, len(pcm) / a.rate))
