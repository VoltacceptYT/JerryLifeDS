#!/usr/bin/env python3
"""Convert every assets/sfx/*.ogg to 8-bit signed PCM arrays in source/sfxdata.c.

    python3 tools/convert_sfx.py [--rate 22050]

Needs ffmpeg + numpy. A sample's name is the file name without ".ogg" and without a leading "jerry_" (jerry_yes2.ogg ->
"yes2", coin.ogg -> "coin"); source/sfx.c plays a random one from a family (yes1, yes2, ... for SFX_YES).
"""
import argparse, glob, os, subprocess
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("--rate", type=int, default=22050)
a = ap.parse_args()
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
files = sorted(glob.glob(os.path.join(root, "assets", "sfx", "*.ogg")))
if not files:
    raise SystemExit("no assets/sfx/*.ogg found")

out = ['// Generated by tools/convert_sfx.py - do not edit.', '#include "sfx.h"', ""]
table, total = [], 0
for i, f in enumerate(files):
    name = os.path.basename(f)[:-len(".ogg")]
    if name.startswith("jerry_"): name = name[len("jerry_"):]
    raw = subprocess.run(["ffmpeg", "-hide_banner", "-v", "error", "-i", f, "-ac", "1", "-ar", str(a.rate),
                          "-f", "f32le", "-"], check=True, stdout=subprocess.PIPE).stdout
    x = np.frombuffer(raw, dtype="<f4").astype(np.float64)
    x = x / (np.max(np.abs(x)) or 1.0) * 0.95          # normalise: 8-bit has little headroom to waste
    pcm = np.clip(np.round(x * 127), -127, 127).astype(np.int8)
    pcm = np.concatenate([pcm, np.zeros((-len(pcm)) % 4, np.int8)])   # whole words for the hardware
    out.append("static const int8_t s%d[%d] __attribute__((aligned(4))) = {%s};" % (i, len(pcm), ",".join(str(int(v)) for v in pcm)))
    table.append('    {"%s", s%d, %d},' % (name, i, len(pcm)))
    total += len(pcm)
    print("%-10s %6d samples (%.2f s)" % (name, len(pcm), len(pcm) / a.rate))
out += ["", "const SfxSample sfx_samples[] = {"] + table + ["};",
        "const int sfx_sample_count = %d;" % len(files), "const unsigned sfx_sample_rate = %d;" % a.rate, ""]
with open(os.path.join(root, "source", "sfxdata.c"), "w", newline="\n") as f:
    f.write("\n".join(out))
print("%d sounds, %.0f KiB" % (len(files), total / 1024))
