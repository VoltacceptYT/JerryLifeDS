def parse(art):
    glyphs, cur = {}, None
    for line in art.strip("\n").split("\n"):
        if line.startswith("@ "):
            p = line[2:].split(" ")
            cur = (p[0], int(p[1]), [])
            glyphs[p[0]] = cur
        else:
            cur[2].append(line)
    return glyphs


def lower_glyphs(size, height):
    """{char: (rows[height], advance)} for a-z of font10 / font14."""
    g = parse(ART10 if size == 10 else ART14)
    out = {}
    for ch, (_, top, art) in g.items():
        assert top + len(art) <= height, (size, ch)
        w = max(len(a) for a in art)
        r = [0] * height
        for i, line in enumerate(art):
            v = 0
            for x, p in enumerate(line):
                if p == "#":
                    v |= 1 << x
            r[top + i] = v
        out[ch] = (r, w + 1)
    return out
