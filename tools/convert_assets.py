def needed_sprites(man):
    atlas = man["atlas"]
    keys = []
    keys += ["skin_" + s["id"] for s in man["skins"]]
    keys += ["food_" + f["id"] for f in man["foods"]]
    keys += ["gift_" + g["id"] for g in man["gifts"]]
    keys += ["toy_" + t["id"] for t in man["toys"]]
    keys += [k for k in atlas if k.startswith("obj_")]
    keys += ["prop_tent", "prop_car", "prop_workbench", "prop_beehive", "prop_snowman"]
    for season in ("spring", "summer", "fall", "winter"):
        keys += ["tree_%s_%d" % (season, n) for n in (1, 2, 3)]
    keys += ["b6_1", "b6_w1", "b1_2", "b1_w2", "b4_3", "b4_w3", "b5_1", "b5_w1"]
    for st in ("b7", "b8"):
        for c in range(1, 7):
            keys += ["%s_%d" % (st, c), "%s_w%d" % (st, c)]
    seen, out = set(), []
    for k in keys:
        assert k in atlas, "missing atlas entry " + k
        if k not in seen:
            seen.add(k)
            out.append(k)
    return sorted(out)


def index_sprite(im):
    """-> (palette colours as (r,g,b), index bytes). 0 transparent, 255 shadow."""
    data = pixels(im)
    opaque = [p[:3] for p in data if p[3] >= 128]
    cols = []
    seen = {}
    for c in opaque:
        if c not in seen:
            seen[c] = len(cols)
            cols.append(c)
    if len(cols) > 254:
        strip = Image.new("RGB", (len(cols), 1))
        strip.putdata(cols)
        q = strip.quantize(colors=254, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
        qp = q.getpalette()
        qi = list(q.getdata())
        used = sorted(set(qi))
        remap = {u: n for n, u in enumerate(used)}
        pal = [tuple(qp[u * 3:u * 3 + 3]) for u in used]
        seen = {c: remap[qi[i]] for i, c in enumerate(cols)}
        cols = pal
    idx = bytearray()
    for p in data:
        if p[3] >= 128:
            idx.append(seen[p[:3]] + 1)
        elif p[3] > 0:
            idx.append(255)
        else:
            idx.append(0)
    return cols, bytes(idx)


def make_atlas(man):
    small = load(os.path.join(A, "jerrylife", "atlas_small.png"))
    build = load(os.path.join(A, "jerrylife", "atlas_build.png"))
    keys = needed_sprites(man)
    blob = bytearray()
    defs = []
    for k in keys:
        x, y, w, h, ax, ay = man["atlas"][k]
        sheet = build if (k.startswith("b") and k[1].isdigit()) else small
        im = sheet.crop((x, y, x + w, y + h))
        if k.startswith("gift_") and im.size == (32, 32):  # one 32x32 gift icon (the staff): shrink to the icon size
            im = halve(im)
            w, h, ax, ay = 16, 16, ax // 2, ay // 2
        cols, idx = index_sprite(im)
        assert len(cols) <= 254
        off = len(blob)
        for c in cols:
            blob += struct.pack("<H", rgb15(c))
        blob += idx
        if len(blob) & 1:
            blob.append(0)
        defs.append((k, w, h, ax, ay, len(cols), off))
    os.makedirs(GEN, exist_ok=True)
    with open(os.path.join(GEN, "atlas.bin"), "wb") as f:
        f.write(bytes(blob))

    hdr = [GENERATED, "#ifndef ATLASDATA_H", "#define ATLASDATA_H", "#include <stdint.h>",
           "/* Indexed sprite: palette (palN x uint16 ARGB1555) at blob+off, then w*h pixel bytes.",
           "   Pixel 0 = transparent, 1..palN = palette[n-1], 255 = soft shadow. (ax, ay) = anchor (feet). */",
           "typedef struct { uint16_t w, h; int16_t ax, ay; uint16_t palN; uint32_t off; } SprDef;",
           "#define SPR_COUNT %d" % len(defs),
           "extern const SprDef spr_defs[SPR_COUNT];",
           "extern const char *const spr_names[SPR_COUNT]; /* sorted */",
           "extern const uint8_t atlas_blob[];  /* assets/gen/atlas.bin, embedded by atlas_data.s */",
           "#endif"]
    out = [GENERATED, '#include "atlasdata.h"', "", "const SprDef spr_defs[SPR_COUNT] = {"]
    for k, w, h, ax, ay, n, off in defs:
        out.append("  {%d, %d, %d, %d, %d, %du}, /* %s */" % (w, h, ax, ay, n, off, k))
    out.append("};")
    out.append("const char *const spr_names[SPR_COUNT] = {")
    out.append(",\n".join('  "%s"' % k for k, *_ in defs))
    out.append("};")
    write(os.path.join(SRC, "atlasdata.h"), "\n".join(hdr) + "\n")
    write(os.path.join(SRC, "atlasdata.c"), "\n".join(out) + "\n")
    print("atlas: %d sprites, %d KiB" % (len(defs), len(blob) // 1024))
    return {k: i for i, (k, *_) in enumerate(defs)}


