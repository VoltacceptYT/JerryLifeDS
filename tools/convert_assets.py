#!/usr/bin/env python3
"""Regenerates the generated sources and data blobs from assets/. Needs Pillow.

    source/gfxdata.c/.h    fonts, UI textures, terrain tiles
    source/atlasdata.c/.h  sprite table (indexed 8bpp sprites, see below) + sprite names
    source/itemdata.c/.h   foods / gifts / toys / skins (from assets/jerrylife/manifest.json)
    assets/gen/atlas.bin   palettes + pixels of every sprite (embedded by source/atlas_data.s)
    icon.bmp               32x32 ROM banner icon

The GitHub Actions workflow runs this before `make`; the generated files are also committed so
local builds work without running it.

Sprite format: every sprite has its own palette (<= 254 ARGB1555 colours). Pixel 0 = transparent,
1..n = palette[n-1], 255 = soft shadow (darkens whatever is underneath).
Sprites come from assets/jerrylife/atlas_small.png and atlas_build.png (rects in manifest.json).
"""
import json, os, struct, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import smallfont
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = os.path.join(ROOT, "assets")
SRC = os.path.join(ROOT, "source")
GEN = os.path.join(A, "gen")

GENERATED = "// GENERATED by tools/convert_assets.py - do not edit."


def load(path):
    return Image.open(path).convert("RGBA")


def scale(im, f):
    return im.resize((im.width * f, im.height * f), Image.NEAREST)


def rgb15(c):
    return (c[0] >> 3) | ((c[1] >> 3) << 5) | ((c[2] >> 3) << 10)


def argb1555(p):
    if p[3] < 128:
        return 0
    return 0x8000 | (p[0] >> 3) | ((p[1] >> 3) << 5) | ((p[2] >> 3) << 10)


def pixels(im):
    return list(im.getdata())


def halve(im):
    """32x32 -> 16x16 keeping existing colours only."""
    from collections import Counter
    out = Image.new("RGBA", (im.width // 2, im.height // 2), (0, 0, 0, 0))
    for y in range(out.height):
        for x in range(out.width):
            px = [im.getpixel((2 * x + dx, 2 * y + dy)) for dx in (0, 1) for dy in (0, 1)]
            px = [p for p in px if p[3] >= 128]
            if px:
                out.putpixel((x, y), Counter(px).most_common(1)[0][0])
    return out


def write(path, text):
    with open(path, "w", newline="\n") as f:
        f.write(text)


# ---------------------------------------------------------------------------
# Fonts (rasterised from JerrifiedPixels.ttf) and UI textures
# ---------------------------------------------------------------------------
FONT = os.path.join(A, "JerrifiedPixels.ttf")
FONT_SIZES = {"font10": 10, "font14": 14}   # rasterised from JerrifiedPixels.ttf (capitals only)
# "fontsm": the small font with lowercase is hand-drawn in tools/smallfont.py


def font_data(size):
    from PIL import ImageFont, ImageDraw
    f = ImageFont.truetype(FONT, size)
    glyphs = []
    for c in range(32, 127):
        im = Image.new("1", (size * 2, size * 3), 0)
        ImageDraw.Draw(im).text((size // 2, size), chr(c), font=f, fill=1)
        glyphs.append((c, im, im.getbbox()))
    top = min(bb[1] for c, im, bb in glyphs if bb)
    bot = max(bb[3] for c, im, bb in glyphs if bb)
    rows, adv = [], []
    for c, im, bb in glyphs:
        if bb is None:
            rows.append([0] * (bot - top))
            adv.append(max(3, size // 4 + 1) if c == 32 else 0)
            continue
        w = bb[2] - bb[0]
        assert w <= 16
        r = []
        for y in range(top, bot):
            v = 0
            for x in range(w):
                if im.getpixel((bb[0] + x, y)):
                    v |= 1 << x
            r.append(v)
        rows.append(r)
        adv.append(w + 1)
    return bot - top, rows, adv


TEXTURES = {"tex_stone": "ui/stone", "tex_button": "ui/button", "tex_ok": "ui/button_ok",
            "tex_cancel": "ui/button_cancel",
            # pressed variants (<name>_active.png), drawn while the button is held
            "tex_button_active": "ui/button_active", "tex_ok_active": "ui/button_ok_active",
            "tex_cancel_active": "ui/button_cancel_active"}

# Terrain: 3x3 autotile blocks (TL,T,TR / L,C,R / BL,B,BR) followed by 4 inner-corner tiles
# (missing SE, SW, NE, NW diagonal). Origins are in sheet pixels (assets/island/island_tiles.png).
TERRAIN_SHEET = os.path.join(A, "island", "island_tiles.png")
TERRAIN_SETS = {"water": ((16, 96), (64, 96)), "grass": ((16, 48), (64, 48))}
TERRAIN_SAND = (0, 64)


def make_gfxdata():
    out = [GENERATED, '#include "gfxdata.h"', ""]
    hdr = [GENERATED, "#ifndef GFXDATA_H", "#define GFXDATA_H", "#include <stdint.h>",
           "typedef struct { const uint16_t *rows; const uint8_t *adv; int height; } Font;"]
    fonts = [("fontsm",) + smallfont.font_data()] + [(n,) + font_data(sz) for n, sz in FONT_SIZES.items()]
    for name, h, rows, adv in fonts:
        out.append("static const uint16_t %s_rows[95 * %d] = {%s};" % (
            name, h, ",".join(str(v) for r in rows for v in r)))
        out.append("static const uint8_t %s_adv[95] = {%s};" % (name, ",".join(map(str, adv))))
        out.append("const Font %s = {%s_rows, %s_adv, %d};" % (name, name, name, h))
        hdr.append("extern const Font %s;" % name)
    for name, rel in TEXTURES.items():
        im = load(os.path.join(A, rel + ".png"))
        assert im.size == (16, 16), rel
        out.append("const uint16_t %s[256] = {%s};" % (name, ",".join(str(argb1555(p)) for p in pixels(im))))
        hdr.append("extern const uint16_t %s[256];" % name)

    sheet = load(TERRAIN_SHEET)

    def tile(x, y):
        return [argb1555(p) for p in pixels(sheet.crop((x, y, x + 16, y + 16)))]

    hdr += ["/* terrain autotile order: TL,T,TR,L,C,R,BL,B,BR, then inner corners missing SE,SW,NE,NW */",
            "#define TER_PIECES 13"]
    sx, sy = TERRAIN_SAND
    out.append("const uint16_t ter_sand[256] = {%s};" % ",".join(map(str, tile(sx, sy))))
    hdr.append("extern const uint16_t ter_sand[256];")
    for name, (o3, oi) in TERRAIN_SETS.items():
        pieces = [tile(o3[0] + 16 * (i % 3), o3[1] + 16 * (i // 3)) for i in range(9)]
        pieces += [tile(oi[0] + 16 * (i % 2), oi[1] + 16 * (i // 2)) for i in range(4)]
        out.append("const uint16_t ter_%s[TER_PIECES][256] = {" % name)
        for t in pieces:
            out.append("  {%s}," % ",".join(map(str, t)))
        out.append("};")
        hdr.append("extern const uint16_t ter_%s[TER_PIECES][256];" % name)
    hdr.append("#endif")
    write(os.path.join(SRC, "gfxdata.c"), "\n".join(out) + "\n")
    write(os.path.join(SRC, "gfxdata.h"), "\n".join(hdr) + "\n")


