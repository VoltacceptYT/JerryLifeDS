TASTES = ["sweet", "savory", "spicy", "drink", "gross"]
CATS = ["fun", "plant", "hero", "magic", "charm", "box", "pet"]


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def make_items(man, sprid):
    for f in man["foods"]:
        assert f["taste"] in TASTES, f
    for g in man["gifts"]:
        assert g["cat"] in CATS, g
    hdr = [GENERATED, "#ifndef ITEMDATA_H", "#define ITEMDATA_H", "#include <stdint.h>",
           "enum { TASTE_SWEET, TASTE_SAVORY, TASTE_SPICY, TASTE_DRINK, TASTE_GROSS, TASTE_COUNT };",
           "enum { CAT_FUN, CAT_PLANT, CAT_HERO, CAT_MAGIC, CAT_CHARM, CAT_BOX, CAT_PET, CAT_COUNT };",
           "#define FOOD_COUNT %d" % len(man["foods"]),
           "#define GIFT_COUNT %d" % len(man["gifts"]),
           "#define TOY_COUNT %d" % len(man["toys"]),
           "#define SKIN_COUNT %d" % len(man["skins"]),
           "typedef struct { const char *id, *name; uint8_t taste; uint16_t price; int16_t spr; } FoodDef;",
           "typedef struct { const char *id, *name; uint8_t cat; uint16_t price; int16_t spr; } GiftDef;",
           "typedef struct { const char *id, *name; uint16_t price; int16_t spr; } ToyDef;",
           "typedef struct { const char *id, *name; int16_t spr; } SkinDef;",
           "extern const FoodDef FOODS[FOOD_COUNT];", "extern const GiftDef GIFTS[GIFT_COUNT];",
           "extern const ToyDef TOYS[TOY_COUNT];", "extern const SkinDef SKINS[SKIN_COUNT];"]
    ids = {t["id"]: i for i, t in enumerate(man["toys"])}
    for i, t in enumerate(man["toys"]):
        hdr.append("#define TOY_%s %d" % (t["id"].upper(), i))
    hdr.append("#endif")
    out = [GENERATED, '#include "itemdata.h"', "", "const FoodDef FOODS[FOOD_COUNT] = {"]
    for f in man["foods"]:
        out.append("  {%s, %s, TASTE_%s, %d, %d}," % (cstr(f["id"]), cstr(f["name"]), f["taste"].upper(), f["price"], sprid["food_" + f["id"]]))
    out += ["};", "const GiftDef GIFTS[GIFT_COUNT] = {"]
    for g in man["gifts"]:
        out.append("  {%s, %s, CAT_%s, %d, %d}," % (cstr(g["id"]), cstr(g["name"]), g["cat"].upper(), g["price"], sprid["gift_" + g["id"]]))
    out += ["};", "const ToyDef TOYS[TOY_COUNT] = {"]
    for t in man["toys"]:
        out.append("  {%s, %s, %d, %d}," % (cstr(t["id"]), cstr(t["name"]), t["price"], sprid["toy_" + t["id"]]))
    out += ["};", "const SkinDef SKINS[SKIN_COUNT] = {"]
    for s in man["skins"]:
        out.append("  {%s, %s, %d}," % (cstr(s["id"]), cstr(s["name"]), sprid["skin_" + s["id"]]))
    out.append("};")
    write(os.path.join(SRC, "itemdata.h"), "\n".join(hdr) + "\n")
    write(os.path.join(SRC, "itemdata.c"), "\n".join(out) + "\n")


SEQUEL_DIGIT = ["###", "..#", "###", "#..", "###"]  # the "2" of Jerry Clicker 2 / Jerry Life


def add_sequel_badge(im):
    """Stamps a gold "2" with a dark outline in the bottom-right corner of the 32x32 icon."""
    gold, edge = (255, 205, 40, 255), (40, 24, 8, 255)
    im = im.copy()
    S = 2
    w, h = 3 * S, 5 * S
    ox, oy = 32 - w - 2, 32 - h - 2           # top-left of the digit, 1 px outline + 1 px margin
    ink = {(ox + x * S + dx, oy + y * S + dy)
           for y, row in enumerate(SEQUEL_DIGIT) for x, c in enumerate(row) if c == "#"
           for dx in range(S) for dy in range(S)}
    for (x, y) in ink:
        for ex in (-1, 0, 1):
            for ey in (-1, 0, 1):
                if (x + ex, y + ey) not in ink:
                    im.putpixel((x + ex, y + ey), edge)
    for (x, y) in ink:
        im.putpixel((x, y), gold)
    return im


def make_icon(man):
    """32x32 4bpp BMP for the ROM banner, from the classic Jerry skin."""
    r = man["atlas"]["skin_jerry"]
    sheet = load(os.path.join(A, "jerrylife", "atlas_small.png"))
    base = scale(sheet.crop((r[0], r[1], r[0] + r[2], r[1] + r[3])), 2)
    assert base.size == (32, 32)
    base = add_sequel_badge(base)
    cols = []
    for p in pixels(base):
        if p[3] >= 128 and p[:3] not in cols:
            cols.append(p[:3])
    assert len(cols) <= 15, len(cols)
    palette = [(255, 0, 255)] + cols
    palette += [(0, 0, 0)] * (16 - len(palette))
    rows = []
    for y in range(31, -1, -1):
        row = bytearray()
        for x in range(0, 32, 2):
            v = []
            for xx in (x, x + 1):
                p = base.getpixel((xx, y))
                v.append(0 if p[3] < 128 else cols.index(p[:3]) + 1)
            row.append((v[0] << 4) | v[1])
        rows.append(bytes(row))
    pix = b"".join(rows)
    pal = b"".join(struct.pack("BBBB", c[2], c[1], c[0], 0) for c in palette)
    off = 14 + 40 + len(pal)
    hdr = b"BM" + struct.pack("<IHHI", off + len(pix), 0, 0, off)
    dib = struct.pack("<IiiHHIIiiII", 40, 32, 32, 1, 4, 0, len(pix), 2835, 2835, 16, 16)
    with open(os.path.join(ROOT, "icon.bmp"), "wb") as f:
        f.write(hdr + dib + pal + pix)


def main():
    with open(os.path.join(A, "jerrylife", "manifest.json")) as f:
        man = json.load(f)
    make_gfxdata()
    sprid = make_atlas(man)
    make_items(man, sprid)
    make_icon(man)
    print("ok")


main()
